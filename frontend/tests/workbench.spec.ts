import {expect,test} from '@playwright/test'
import {resolve} from 'node:path'

test('ZIP → editable workflow → live execution → report and settings',async({page})=>{
 const errors:string[]=[]
 page.on('pageerror',e=>errors.push(e.message))
 await page.goto('/')
 await expect(page.getByRole('heading',{name:'Обзор проверок'})).toBeVisible()
 await page.screenshot({path:resolve('../.qa/dashboard.png'),fullPage:true})
 await page.getByRole('link',{name:'Добавить проект'}).click()
 await page.getByLabel('Название',{exact:true}).fill('Проверка в браузере')
 await page.locator('input[type=file]').setInputFiles(resolve('../.qa/e2e-fixture.zip'))
 await page.getByRole('button',{name:'Создать проект'}).click()
 await expect(page.getByRole('heading',{name:'Проверка в браузере'})).toBeVisible()
 await page.getByRole('link',{name:'Создать сценарий'}).click()
 await page.getByRole('button',{name:'Открыть редактор'}).click()
 await expect(page.locator('.react-flow__node')).toHaveCount(6)
 await page.getByLabel('Название сценария').fill('Приёмочная проверка')
 await page.getByRole('button',{name:'Regex',exact:true}).click()
 await expect(page.getByLabel('Выражение для пути')).toBeVisible()
 await page.getByRole('button',{name:'Удалить узел'}).click()
 await page.getByRole('button',{name:'Проверить',exact:true}).click()
 await expect(page.getByText('Граф прошёл проверку')).toBeVisible()
 await page.screenshot({path:resolve('../.qa/editor.png'),fullPage:true})
 await page.getByRole('button',{name:'Запустить',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Выполнение графа'})).toBeVisible()
 await expect(page.getByText('2 находок в итоговом отчёте.')).toBeVisible()
 const download=page.waitForEvent('download')
 await page.getByRole('link',{name:'JSON',exact:true}).click()
 expect((await download).suggestedFilename()).toMatch(/\.json$/)
 await page.getByRole('link',{name:'Открыть находки'}).click()
 await page.getByLabel('Категория',{exact:true}).selectOption('SECRET')
 await page.getByRole('button',{name:'Подробности находки'}).click()
 await expect(page.getByRole('dialog')).toContainText('Значение скрыто')
 await page.getByRole('button',{name:'Закрыть',exact:true}).click()
 await page.getByRole('link',{name:'Настройки',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Telegram'})).toBeVisible()
 await page.setViewportSize({width:390,height:844})
 await page.getByRole('link',{name:'Обзор',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Обзор проверок'})).toBeVisible()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 expect(errors).toEqual([])
})
